CREATE VIEW public.film_scores WITH(security_invoker=true) AS
 SELECT p.id AS pelicula_id,p.slug,
  (SELECT count(*) FROM public.ratings r WHERE r.pelicula_id=p.id) AS rating_count,
  (SELECT round((avg(r.score)*20)::numeric,2) FROM public.ratings r WHERE r.pelicula_id=p.id) AS approval_score,
  (SELECT count(*) FROM public.view_history v WHERE v.pelicula_id=p.id) AS view_count
 FROM public.peliculas p;
