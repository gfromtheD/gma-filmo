-- Invoked by seed only after engine migrations. Keeps live fixture reservations intact.
CREATE FUNCTION public.gma_media_local_inventory() RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE f gma_media_local_fixture; b bigint; r record;
BEGIN
  SELECT * INTO f FROM gma_media_local_fixture WHERE id FOR UPDATE;
  IF NOT FOUND OR f.project_id<>'gma-filmo-media-local' THEN RAISE EXCEPTION 'MEDIA_LOCAL_FIXTURE_REQUIRED'; END IF;
  IF EXISTS(SELECT 1 FROM peliculas WHERE playback_kind='legacy' AND r2_video_url IS NOT NULL
    AND (r2_video_url<>'http://127.0.0.1:4319/fixtures/legacy.mp4' OR file_size_bytes IS NULL)) THEN
    RAISE EXCEPTION 'MEDIA_LOCAL_INVENTORY_UNVERIFIED';
  END IF;
  SELECT COALESCE(sum(file_size_bytes),0) INTO b FROM peliculas
    WHERE playback_kind='legacy' AND r2_video_url='http://127.0.0.1:4319/fixtures/legacy.mp4';
  IF NOT f.inventory_seeded THEN
    INSERT INTO gma_upload_quota(account_key,used_bytes) VALUES('global',b)
      ON CONFLICT(account_key) DO UPDATE SET used_bytes=gma_upload_quota.used_bytes+EXCLUDED.used_bytes;
    FOR r IN SELECT creator_user_id,COALESCE(sum(file_size_bytes),0) AS bytes FROM peliculas
      WHERE playback_kind='legacy' AND r2_video_url='http://127.0.0.1:4319/fixtures/legacy.mp4' AND creator_user_id IS NOT NULL
      GROUP BY creator_user_id LOOP
      INSERT INTO gma_upload_quota(account_key,used_bytes) VALUES('owner:'||r.creator_user_id::text,r.bytes)
        ON CONFLICT(account_key) DO UPDATE SET used_bytes=gma_upload_quota.used_bytes+EXCLUDED.used_bytes;
    END LOOP;
    UPDATE gma_media_local_fixture SET inventory_seeded=true,inventory_bytes=b WHERE id;
  ELSIF f.inventory_bytes<>b THEN
    RAISE EXCEPTION 'MEDIA_LOCAL_INVENTORY_CHANGED';
  END IF;
  UPDATE gma_upload_policy SET legacy_inventory_verified=true WHERE id;
  RETURN jsonb_build_object('project_id',f.project_id,'legacy_bytes',b,'inventory_verified',true);
END $$;
REVOKE ALL ON FUNCTION public.gma_media_local_inventory() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.gma_media_local_inventory() TO service_role;
COMMIT;
